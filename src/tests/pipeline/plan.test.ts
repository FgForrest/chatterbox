import { describe, expect, it } from "vitest";
import { planAdvance } from "@/lib/pipeline/plan";
import type {
    PhaseRecord,
    PipelineAction,
    PipelineFacts,
    PipelineProfileFacts,
} from "@/lib/pipeline/types";

const AT = "2026-10-14T12:00:00.000Z";
const DEFAULT_PROFILE: PipelineProfileFacts = {
    revisionId: "profile-revision-1",
    automatic: {
        learn: false,
        summary: true,
        title: true,
        topics: true,
    },
};

function phase(
    state: PhaseRecord["state"],
    reason: string,
    generation = 4,
): PhaseRecord {
    return { state, reason, generation, at: AT };
}

function profileAutomatic(
    overrides: Partial<PipelineProfileFacts["automatic"]>,
): PipelineProfileFacts {
    return {
        ...DEFAULT_PROFILE,
        automatic: { ...DEFAULT_PROFILE.automatic, ...overrides },
    };
}

function audioFacts(overrides: Partial<PipelineFacts> = {}): PipelineFacts {
    const base: PipelineFacts = {
        item: {
            exists: true,
            deleted: false,
            kind: "audio",
            ownerUserId: "user-1",
        },
        view: "private",
        generation: 4,
        content: {
            contentId: "transcription-1",
            contentSourceId: "riffado",
            contentRevision: 7,
            timed: true,
        },
        summaryDueAt: null,
        profile: { ...DEFAULT_PROFILE },
        categorization: {
            placementFolderIds: ["folder-1"],
            intendedFolderIds: [],
            profileAssigned: true,
            resolution: "resolved",
        },
        hasEnhancementCredential: true,
        mail: null,
        summary: { exists: false, stale: false, jobActive: false },
        taskReview: { proposals: 0, followUps: 0 },
        phases: {
            categorize: phase("done", "categorized"),
            transcribe: {
                ...phase("done", "content-available"),
                inputs: {
                    contentId: "transcription-1",
                    contentSourceId: "riffado",
                    contentRevision: 7,
                },
            },
            learn: {
                ...phase("skipped", "disabled"),
                inputs: {
                    contentId: "transcription-1",
                    contentSourceId: "riffado",
                    contentRevision: 7,
                },
            },
        },
        at: AT,
    };
    return {
        ...base,
        ...overrides,
        phases: { ...base.phases, ...overrides.phases },
    };
}

function mailFacts(overrides: Partial<PipelineFacts> = {}): PipelineFacts {
    const base = audioFacts({
        item: {
            exists: true,
            deleted: false,
            kind: "mail",
            ownerUserId: "user-1",
        },
        content: {
            contentId: "mail-content-1",
            contentSourceId: "mail",
            contentRevision: 3,
            timed: false,
        },
        mail: { autoGenerated: false, unreadable: false, shared: false },
        phases: {
            categorize: phase("done", "categorized"),
            transcribe: phase("skipped", "not-applicable"),
            learn: {
                ...phase("skipped", "disabled"),
                inputs: {
                    contentId: "mail-content-1",
                    contentSourceId: "mail",
                    contentRevision: 3,
                },
            },
        },
    });
    if (overrides.profile?.automatic.learn) delete base.phases.learn;
    return {
        ...base,
        ...overrides,
        phases: { ...base.phases, ...overrides.phases },
    };
}

function actionTypes(actions: PipelineAction[]): string[] {
    return actions.map((action) => action.type);
}

function applyMarks(facts: PipelineFacts, actions: PipelineAction[]) {
    const phases = { ...facts.phases };
    for (const action of actions) {
        if (action.type === "markPhase") phases[action.phase] = action.record;
    }
    return { ...facts, phases };
}

function releasedLearn(
    contentRevision = 7,
    generation = 4,
    contentId = "transcription-1",
): PhaseRecord {
    return {
        state: "done",
        reason: "released",
        generation,
        inputs: { contentId, contentSourceId: "riffado", contentRevision },
        at: AT,
    };
}

describe("planAdvance audio", () => {
    it("waits for a folder before planning any later phase", () => {
        const result = planAdvance(
            audioFacts({
                categorization: {
                    placementFolderIds: [],
                    intendedFolderIds: [],
                    profileAssigned: false,
                    resolution: null,
                },
                phases: {
                    categorize: undefined,
                    transcribe: undefined,
                    learn: undefined,
                },
            }),
        );

        expect(result.actions).toEqual([
            {
                type: "markPhase",
                phase: "categorize",
                record: phase("waiting", "needs_folder"),
            },
        ]);
    });

    it("waits for the owner when placement profile resolution needs a choice", () => {
        const result = planAdvance(
            audioFacts({
                categorization: {
                    placementFolderIds: ["folder-1", "folder-2"],
                    intendedFolderIds: [],
                    profileAssigned: false,
                    resolution: "choose",
                },
                profile: null,
                phases: {
                    categorize: undefined,
                    transcribe: undefined,
                    learn: undefined,
                },
            }),
        );

        expect(result.actions).toEqual([
            {
                type: "markPhase",
                phase: "categorize",
                record: phase("waiting", "needs_profile"),
            },
        ]);
    });

    it("marks Categorize done once placement and the frozen profile are set", () => {
        const result = planAdvance(
            audioFacts({
                phases: {
                    categorize: undefined,
                    transcribe: undefined,
                    learn: undefined,
                },
            }),
        );

        expect(result.actions[0]).toEqual({
            type: "markPhase",
            phase: "categorize",
            record: phase("done", "categorized"),
        });
        expect(actionTypes(result.actions)).toContain("queueSummary");
    });

    it("does not start a later phase until Categorize is done", () => {
        const facts = audioFacts({
            phases: { categorize: phase("waiting", "needs_folder") },
            categorization: {
                placementFolderIds: [],
                intendedFolderIds: [],
                profileAssigned: false,
                resolution: null,
            },
        });

        expect(planAdvance(facts).actions).toEqual([]);
    });

    it("records Transcribe and Learn phase decisions without changing queued Stage 2 work", () => {
        const facts = audioFacts({
            phases: {
                categorize: phase("done", "categorized"),
                transcribe: undefined,
                learn: undefined,
            },
        });
        const actions = planAdvance(facts).actions;

        expect(actions.slice(0, 2)).toEqual([
            expect.objectContaining({
                type: "markPhase",
                phase: "transcribe",
                record: expect.objectContaining({
                    state: "done",
                    reason: "content-available",
                }),
            }),
            expect.objectContaining({
                type: "markPhase",
                phase: "learn",
                record: expect.objectContaining({
                    state: "skipped",
                    reason: "disabled",
                }),
            }),
        ]);
        expect(actionTypes(actions)).toEqual([
            "markPhase",
            "markPhase",
            "queueTopics",
            "markPhase",
            "queueSummary",
            "markPhase",
        ]);
    });

    it("waits at Task review while proposals or follow-ups remain", () => {
        const facts = audioFacts({
            taskReview: { proposals: 1, followUps: 2 },
            phases: {
                ...audioFacts().phases,
                summary: {
                    ...phase("done", "generated"),
                    inputs: {
                        contentId: "transcription-1",
                        contentSourceId: "riffado",
                        contentRevision: 7,
                    },
                    steps: {
                        summary: {
                            contentId: "transcription-1",
                            contentRevision: 7,
                            generation: 4,
                        },
                        topics: {
                            contentId: "transcription-1",
                            contentRevision: 7,
                            generation: 4,
                        },
                    },
                },
            },
            summary: { exists: true, stale: false, jobActive: false },
        });

        expect(planAdvance(facts).actions).toEqual([
            {
                type: "markPhase",
                phase: "taskReview",
                record: phase("waiting", "needs_review"),
            },
        ]);
    });

    it("does not decide Task review after the proposals disappear", () => {
        const facts = audioFacts({
            phases: {
                ...audioFacts().phases,
                taskReview: phase("waiting", "needs_review"),
            },
        });

        expect(planAdvance(facts).actions).toEqual([
            { type: "queueTopics", strict: false },
            expect.objectContaining({ type: "markPhase", phase: "summary" }),
            {
                type: "queueSummary",
                presetId: null,
                strict: false,
            },
            expect.objectContaining({ type: "markPhase", phase: "summary" }),
        ]);
        expect(
            planAdvance(facts).actions.some(
                (action) =>
                    action.type === "markPhase" &&
                    action.phase === "taskReview",
            ),
        ).toBe(false);
    });

    it("leaves a legacy item idle until its content identity changes", () => {
        const legacy = audioFacts({
            phases: {
                categorize: phase("done", "legacy", 0),
                learn: {
                    ...phase("done", "legacy", 0),
                    inputs: {
                        contentId: "transcription-1",
                        contentSourceId: "riffado",
                        contentRevision: 7,
                    },
                },
                summary: {
                    ...phase("done", "legacy", 0),
                    inputs: {
                        contentId: "transcription-1",
                        contentSourceId: "riffado",
                        contentRevision: 7,
                    },
                    steps: Object.fromEntries(
                        ["title", "topics", "summary"].map((step) => [
                            step,
                            {
                                contentId: "transcription-1",
                                contentRevision: 7,
                                generation: 0,
                            },
                        ]),
                    ),
                },
            },
            categorization: {
                placementFolderIds: ["folder-1"],
                intendedFolderIds: [],
                profileAssigned: false,
                resolution: "resolved",
            },
        });

        expect(planAdvance(legacy).actions).toEqual([]);
        expect(
            actionTypes(
                planAdvance({
                    ...legacy,
                    generation: 5,
                    content: {
                        contentId: "transcription-1",
                        contentSourceId: "riffado",
                        contentRevision: 8,
                        timed: true,
                    },
                }).actions,
            ),
        ).toContain("queueSummary");
    });
    it.each([
        {
            name: "an active Learn hold",
            facts: audioFacts({ summaryDueAt: AT }),
            expected: ["markPhase"],
        },
        {
            name: "a timed transcript",
            facts: audioFacts(),
            expected: ["queueTopics", "markPhase", "queueSummary", "markPhase"],
        },
        {
            name: "automatic titles off (the inline title remains at the trigger)",
            facts: audioFacts({
                profile: profileAutomatic({ title: false }),
            }),
            expected: ["queueTopics", "markPhase", "queueSummary", "markPhase"],
        },
        {
            name: "an untimed transcript",
            facts: audioFacts({
                content: {
                    contentId: "transcription-1",
                    contentSourceId: "riffado",
                    contentRevision: 7,
                    timed: false,
                },
            }),
            expected: ["queueSummary", "markPhase"],
        },
        {
            name: "the Organization view",
            facts: audioFacts({ view: "org" }),
            expected: [],
        },
        {
            name: "automatic summaries off",
            facts: audioFacts({
                profile: profileAutomatic({ summary: false }),
            }),
            expected: ["queueTopics", "markPhase"],
        },
    ])("reproduces the transcript path for $name", ({ facts, expected }) => {
        expect(actionTypes(planAdvance(facts).actions)).toEqual(expected);
    });

    it.each([
        {
            name: "missing summary",
            summary: { exists: false, stale: false, jobActive: false },
            expectedSummary: true,
        },
        {
            name: "stale summary",
            summary: { exists: true, stale: true, jobActive: false },
            expectedSummary: true,
        },
        {
            name: "fresh summary",
            summary: { exists: true, stale: false, jobActive: false },
            expectedSummary: false,
        },
        {
            name: "active summary job",
            summary: { exists: false, stale: false, jobActive: true },
            expectedSummary: false,
        },
    ])("reproduces the release path for $name", ({
        summary,
        expectedSummary,
    }) => {
        const result = planAdvance(
            audioFacts({ phases: { learn: releasedLearn() }, summary }),
        );
        expect(actionTypes(result.actions)).toEqual([
            ...(expectedSummary ? ["queueSummary", "markPhase"] : []),
            "queueTopics",
            "markPhase",
            "queueTitleJob",
            "markPhase",
        ]);
        for (const action of result.actions) {
            if (
                action.type === "queueSummary" ||
                action.type === "queueTopics"
            ) {
                expect(action.strict).toBe(true);
            }
        }
    });

    it("queues strict topics even when release-time auto-summary is off", () => {
        const facts = audioFacts({
            phases: { learn: releasedLearn() },
            profile: profileAutomatic({ summary: false }),
        });
        expect(actionTypes(planAdvance(facts).actions)).toEqual([
            "queueTopics",
            "markPhase",
            "queueTitleJob",
            "markPhase",
        ]);
    });

    it("does not queue a release-time title when automatic titles are off", () => {
        const facts = audioFacts({
            phases: { learn: releasedLearn() },
            profile: profileAutomatic({ title: false }),
        });
        expect(actionTypes(planAdvance(facts).actions)).toEqual([
            "queueSummary",
            "markPhase",
            "queueTopics",
            "markPhase",
        ]);
    });

    it("uses the seeded profile's release-time title automation", () => {
        const facts = audioFacts({
            phases: { learn: releasedLearn() },
            profile: profileAutomatic({ summary: false }),
        });
        expect(actionTypes(planAdvance(facts).actions)).toEqual([
            "queueTopics",
            "markPhase",
            "queueTitleJob",
            "markPhase",
        ]);
    });

    it("uses the release path after a synchronous Learn release", () => {
        const facts = audioFacts({
            phases: { learn: releasedLearn(7, 5) },
            generation: 5,
        });
        expect(actionTypes(planAdvance(facts).actions)).toEqual([
            "queueSummary",
            "markPhase",
            "queueTopics",
            "markPhase",
            "queueTitleJob",
            "markPhase",
        ]);
    });

    it("waits while held, then takes the release path", () => {
        const held = audioFacts({ summaryDueAt: AT });
        const waiting = planAdvance(held);
        expect(actionTypes(waiting.actions)).toEqual(["markPhase"]);

        const released = applyMarks(held, waiting.actions);
        released.summaryDueAt = null;
        released.generation = 5;
        released.phases.learn = releasedLearn(7, 5);
        expect(actionTypes(planAdvance(released).actions)).toEqual([
            "queueSummary",
            "markPhase",
            "queueTopics",
            "markPhase",
            "queueTitleJob",
            "markPhase",
        ]);
    });

    it("does not repeat the waiting mark for the same held generation", () => {
        const held = audioFacts({ summaryDueAt: AT });
        const first = planAdvance(held);
        expect(planAdvance(applyMarks(held, first.actions)).actions).toEqual(
            [],
        );
    });

    it("uses the transcript path for a newer transcript than the released one", () => {
        const facts = audioFacts({
            content: {
                contentId: "transcription-1",
                contentSourceId: "riffado",
                contentRevision: 8,
                timed: true,
            },
            phases: { learn: releasedLearn(7, 4) },
            generation: 5,
        });
        expect(actionTypes(planAdvance(facts).actions)).toEqual([
            "markPhase",
            "markPhase",
            "queueTopics",
            "markPhase",
            "queueSummary",
            "markPhase",
        ]);
    });

    it.each([
        {
            name: "a missing item",
            item: { ...audioFacts().item, exists: false },
        },
        {
            name: "a deleted item",
            item: { ...audioFacts().item, deleted: true },
        },
        {
            name: "an audio item with non-Riffado content",
            item: audioFacts().item,
            content: {
                contentId: "mail-content-1",
                contentSourceId: "mail",
                contentRevision: 3,
                timed: false,
            },
        },
    ])("reports gone for $name", ({ item, content = audioFacts().content }) => {
        expect(planAdvance(audioFacts({ item, content }))).toEqual({
            actions: [],
            reason: "gone",
        });
    });

    it("waits in Transcribe when categorized audio has no content", () => {
        expect(planAdvance(audioFacts({ content: null })).actions).toEqual([
            expect.objectContaining({
                type: "markPhase",
                phase: "transcribe",
                record: expect.objectContaining({
                    state: "waiting",
                    reason: "needs_transcript",
                }),
            }),
        ]);
    });

    it("emits every queue action immediately before its durable mark", () => {
        const actions = planAdvance(
            audioFacts({ phases: { learn: releasedLearn() } }),
        ).actions;
        actions.forEach((action, index) => {
            if (action.type.startsWith("queue")) {
                expect(actions[index + 1]?.type).toBe("markPhase");
            }
        });
    });

    it("carries transcript arguments and the requested revision in marks", () => {
        expect(planAdvance(audioFacts()).actions).toEqual([
            { type: "queueTopics", strict: false },
            {
                type: "markPhase",
                phase: "summary",
                record: expect.objectContaining({
                    generation: 4,
                    profileRevisionId: "profile-revision-1",
                    steps: {
                        topics: {
                            contentId: "transcription-1",
                            contentRevision: 7,
                            generation: 4,
                            profileRevisionId: "profile-revision-1",
                        },
                    },
                }),
            },
            {
                type: "queueSummary",
                presetId: null,
                strict: false,
            },
            {
                type: "markPhase",
                phase: "summary",
                record: expect.objectContaining({
                    generation: 4,
                    profileRevisionId: "profile-revision-1",
                    steps: {
                        topics: {
                            contentId: "transcription-1",
                            contentRevision: 7,
                            generation: 4,
                            profileRevisionId: "profile-revision-1",
                        },
                        summary: {
                            contentId: "transcription-1",
                            contentRevision: 7,
                            generation: 4,
                            profileRevisionId: "profile-revision-1",
                        },
                    },
                }),
            },
        ]);
    });

    it("does not repeat actions after their marks are applied", () => {
        const facts = audioFacts({ phases: { learn: releasedLearn() } });
        const first = planAdvance(facts);
        expect(first.actions.length).toBeGreaterThan(0);
        expect(planAdvance(applyMarks(facts, first.actions)).actions).toEqual(
            [],
        );
    });

    it("requests summary steps again for a replacement content row at the same revision", () => {
        const facts = audioFacts();
        const first = planAdvance(facts);
        const replaced = applyMarks(facts, first.actions);
        if (!facts.content) throw new Error("expected audio content");
        replaced.content = {
            ...facts.content,
            contentId: "transcription-2",
        };
        expect(actionTypes(planAdvance(replaced).actions)).toEqual([
            "markPhase",
            "markPhase",
            "queueTopics",
            "markPhase",
            "queueSummary",
            "markPhase",
        ]);
    });

    it("does not use a stale Learn release from a replaced content row", () => {
        const facts = audioFacts({
            phases: {
                learn: releasedLearn(7, 4, "erased-transcription"),
            },
        });
        expect(actionTypes(planAdvance(facts).actions)).toEqual([
            "markPhase",
            "queueTopics",
            "markPhase",
            "queueSummary",
            "markPhase",
        ]);
    });
});

describe("planAdvance mail", () => {
    it("waits for a profile choice before starting mail phases", () => {
        const result = planAdvance(
            mailFacts({
                categorization: {
                    placementFolderIds: ["folder-1", "folder-2"],
                    intendedFolderIds: [],
                    profileAssigned: false,
                    resolution: "choose",
                },
                profile: null,
                phases: {
                    categorize: undefined,
                    transcribe: undefined,
                    learn: undefined,
                },
            }),
        );

        expect(result.actions).toEqual([
            {
                type: "markPhase",
                phase: "categorize",
                record: phase("waiting", "needs_profile"),
            },
        ]);
    });

    it.each([
        {
            autoGenerated: true,
            unreadable: false,
            reason: "machine_sent",
        },
        {
            autoGenerated: false,
            unreadable: true,
            reason: "unreadable",
        },
    ])("marks terminal mail as not processed: $reason", (mail) => {
        const result = planAdvance(
            mailFacts({
                mail: { ...mail, shared: false },
                phases: {},
            }),
        );

        expect(result.actions).toEqual([
            {
                type: "markPhase",
                phase: "categorize",
                record: phase("not_processed", mail.reason),
            },
        ]);
    });
    it.each([
        {
            name: "mail auto-processing off",
            facts: mailFacts({
                profile: profileAutomatic({ summary: false, learn: false }),
            }),
            expected: [],
        },
        {
            name: "machine-sent mail",
            facts: mailFacts({
                mail: { autoGenerated: true, unreadable: false, shared: false },
            }),
            expected: ["markPhase"],
        },
        {
            name: "unreadable mail",
            facts: mailFacts({
                mail: { autoGenerated: false, unreadable: true, shared: false },
            }),
            expected: ["markPhase"],
        },
        {
            name: "no enhancement credential",
            facts: mailFacts({ hasEnhancementCredential: false }),
            expected: [],
        },
        {
            name: "normal mail without Learn",
            facts: mailFacts(),
            expected: ["queueSummary", "markPhase"],
        },
        {
            name: "normal mail with Learn",
            facts: mailFacts({
                profile: profileAutomatic({ learn: true }),
            }),
            expected: [
                "queueSummary",
                "markPhase",
                "startAutoLearnMail",
                "markPhase",
            ],
        },
        {
            name: "the seeded mail profile",
            facts: mailFacts(),
            expected: ["queueSummary", "markPhase"],
        },
        {
            name: "already shared mail",
            facts: mailFacts({
                profile: profileAutomatic({ learn: true }),
                mail: { autoGenerated: false, unreadable: false, shared: true },
            }),
            expected: [
                "queueSummary",
                "markPhase",
                "startAutoLearnMail",
                "markPhase",
            ],
        },
    ])("reproduces $name", ({ facts, expected }) => {
        expect(actionTypes(planAdvance(facts).actions)).toEqual(expected);
    });

    it("does not repeat mail actions after their marks are applied", () => {
        const facts = mailFacts({
            profile: profileAutomatic({ learn: true }),
        });
        const first = planAdvance(facts);
        expect(planAdvance(applyMarks(facts, first.actions)).actions).toEqual(
            [],
        );
    });

    it("queues mail summary with no preset and non-strict delivery", () => {
        expect(planAdvance(mailFacts()).actions[0]).toEqual({
            type: "queueSummary",
            presetId: null,
            strict: false,
        });
    });

    it("plans mail content from the mail source", () => {
        const actions = planAdvance(mailFacts()).actions;
        expect(actionTypes(actions)).toEqual(["queueSummary", "markPhase"]);
        expect(actions[1]).toEqual(
            expect.objectContaining({
                record: expect.objectContaining({
                    inputs: {
                        contentId: "mail-content-1",
                        contentSourceId: "mail",
                        contentRevision: 3,
                    },
                }),
            }),
        );
    });

    it("waits for parsed mail content", () => {
        expect(planAdvance(mailFacts({ content: null })).actions).toEqual([
            expect.objectContaining({
                type: "markPhase",
                phase: "learn",
                record: expect.objectContaining({
                    state: "waiting",
                    reason: "needs_content",
                }),
            }),
        ]);
    });

    it("does nothing on the Organization view", () => {
        expect(planAdvance(mailFacts({ view: "org" })).actions).toEqual([]);
    });
});
