// @vitest-environment jsdom

import {
    cleanup,
    fireEvent,
    render,
    screen,
    waitFor,
} from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { RecordingList } from "@/components/dashboard/recording-list";
import type { Recording } from "@/types/recording";

vi.mock("next-intl", () => ({
    useExtracted:
        () =>
        (
            input: string | { message: string },
            values?: Record<string, string | number>,
        ) => {
            const message = typeof input === "string" ? input : input.message;
            const count = Number(values?.count ?? 0);
            if (message === "{count, plural, one {# item} other {# items}}") {
                return count === 1 ? "1 item" : `${count} items`;
            }
            return message.replace("{count}", String(values?.count ?? ""));
        },
    useLocale: () => "en",
}));

vi.mock("@/components/dashboard/recording-row", () => ({
    RecordingRow: ({ recording }: { recording: Recording }) => (
        <div>{recording.filename}</div>
    ),
}));

class TestIntersectionObserver {
    observe() {}
    disconnect() {}
}

const recordings: Recording[] = [
    {
        id: "audio",
        filename: "Weekly recording",
        duration: 1_000,
        startTime: "2026-10-16T10:00:00.000Z",
        filesize: 1_000,
        deviceSn: "audio",
    },
    {
        id: "mail",
        kind: "mail",
        filename: "Weekly mail",
        duration: 0,
        startTime: "2026-10-16T11:00:00.000Z",
        filesize: 500,
        deviceSn: "mail",
        mail: {
            from: "sender@example.com",
            senderVerified: true,
            hasAttachments: false,
            waitingToShare: false,
            autoGenerated: false,
        },
    },
];

function renderList({
    items = recordings,
    mailEnabled = false,
}: {
    items?: Recording[];
    mailEnabled?: boolean;
} = {}) {
    return render(
        <RecordingList
            recordings={items}
            mailEnabled={mailEnabled}
            transcriptions={new Map()}
            currentRecording={items[0] ?? null}
            pendingUploads={[]}
            inFlightActions={new Map()}
            onSelect={vi.fn()}
            onDelete={vi.fn()}
            initialDateTimeFormat="relative"
            initialSortOrder="newest"
            initialKindFilter="all"
            initialChunkSize={50}
        />,
    );
}

function openMenu(name = "All · Newest") {
    fireEvent.pointerDown(screen.getByRole("button", { name }), {
        button: 0,
        ctrlKey: false,
    });
}

beforeEach(() => {
    vi.stubGlobal("IntersectionObserver", TestIntersectionObserver);
});

afterEach(() => {
    cleanup();
    vi.unstubAllGlobals();
});

describe("Chatter list toolbar", () => {
    it("shows one item count and names the channel and sort state", () => {
        vi.stubGlobal("fetch", vi.fn());
        renderList();

        expect(screen.getByText("2 items")).toBeTruthy();
        expect(screen.queryByText(/2 of 2 2/)).toBeNull();
        expect(
            screen.getByRole("button", { name: "All · Newest" }),
        ).toBeTruthy();
    });

    it("keeps one channel selected and persists each valid change", async () => {
        const fetchMock = vi.fn().mockResolvedValue(Response.json({}));
        vi.stubGlobal("fetch", fetchMock);
        renderList();
        openMenu();

        fireEvent.click(
            screen.getByRole("menuitemcheckbox", { name: "Mail1" }),
        );
        expect(
            screen.getByRole("menu", { name: "Recordings · Newest" }),
        ).toBeTruthy();
        expect(
            screen
                .getByRole("menuitemcheckbox", { name: "Recordings1" })
                .getAttribute("data-disabled"),
        ).toBe("");
        fireEvent.click(
            screen.getByRole("menuitemcheckbox", { name: "Recordings1" }),
        );
        expect(screen.getByText("1 item")).toBeTruthy();

        await waitFor(() => {
            expect(fetchMock).toHaveBeenCalledWith(
                "/api/settings/user",
                expect.objectContaining({
                    method: "PUT",
                    body: JSON.stringify({ chatterKindFilter: "audio" }),
                }),
            );
        });
    });

    it("sends the selected search scopes to the search endpoint", async () => {
        const fetchMock = vi.fn(async (input: RequestInfo | URL) => {
            if (String(input).startsWith("/api/items/search?")) {
                return Response.json({
                    hits: [],
                    complete: true,
                    continueBefore: null,
                });
            }
            return Response.json({});
        });
        vi.stubGlobal("fetch", fetchMock);
        renderList();
        openMenu();
        fireEvent.click(
            screen.getByRole("menuitemcheckbox", { name: "Titles" }),
        );
        fireEvent.click(
            screen.getByRole("menuitemcheckbox", { name: "Summaries" }),
        );
        expect(
            screen
                .getByRole("menuitemcheckbox", {
                    name: "Transcripts and message text",
                })
                .getAttribute("data-disabled"),
        ).toBe("");

        const searchInput = document.querySelector<HTMLInputElement>(
            'input[aria-label="Search recordings"]',
        );
        expect(searchInput).not.toBeNull();
        if (searchInput) {
            fireEvent.change(searchInput, { target: { value: "weekly" } });
        }

        await waitFor(() => {
            const searchCall = fetchMock.mock.calls.find(([input]) =>
                String(input).startsWith("/api/items/search?"),
            );
            expect(searchCall).toBeTruthy();
            expect(String(searchCall?.[0])).toContain("scope=content");
        });
    });

    it("sorts from the combined menu and persists the choice", async () => {
        const fetchMock = vi.fn().mockResolvedValue(Response.json({}));
        vi.stubGlobal("fetch", fetchMock);
        renderList();
        openMenu();
        fireEvent.click(screen.getByRole("menuitemradio", { name: "Name" }));

        expect(screen.getByRole("button", { name: "All · Name" })).toBeTruthy();
        await waitFor(() => {
            expect(fetchMock).toHaveBeenCalledWith(
                "/api/settings/user",
                expect.objectContaining({
                    body: JSON.stringify({ recordingListSortOrder: "name" }),
                }),
            );
        });
    });

    it("offers no channel choice without mail", () => {
        vi.stubGlobal("fetch", vi.fn());
        renderList({ items: recordings.filter((r) => r.kind !== "mail") });
        openMenu("Newest");

        expect(
            screen.queryByRole("menuitemcheckbox", { name: /Mail/ }),
        ).toBeNull();
        expect(
            screen.queryByRole("menuitemcheckbox", { name: /Recordings/ }),
        ).toBeNull();
    });

    it("offers the Mail channel where mail is enabled before any arrives", () => {
        vi.stubGlobal("fetch", vi.fn());
        renderList({
            items: recordings.filter((r) => r.kind !== "mail"),
            mailEnabled: true,
        });
        openMenu();

        expect(
            screen.getByRole("menuitemcheckbox", { name: "Mail0" }),
        ).toBeTruthy();
    });
});
