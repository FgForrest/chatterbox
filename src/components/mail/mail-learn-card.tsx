"use client";

import { LearnWidget } from "@/components/learn/learn-widget";
import type { MailDetail } from "@/lib/mail/detail";
import type { WorkflowWidgetState } from "@/lib/pipeline/workflow-widgets";
import type { Recording } from "@/types/recording";

/** Connect a mail detail to the shared Learn widget. */
export function MailLearnCard({
    mail,
    detail,
    canChange,
    widget,
    widgetId,
}: {
    mail: Recording;
    detail: MailDetail;
    canChange: boolean;
    widget?: WorkflowWidgetState;
    widgetId: string;
}) {
    if (!canChange || mail.mail?.autoGenerated || detail.unreadable) {
        return null;
    }

    return (
        <LearnWidget
            kind="mail"
            recordingId={mail.id}
            view={mail.view}
            mailDetail={detail}
            frame={widget?.frame ?? "inline"}
            widgetId={widgetId}
            showTrigger={false}
            collapseReady
        />
    );
}
