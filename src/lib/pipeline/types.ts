export type PipelineView = "private" | "org";

export type PhaseName =
    | "categorize"
    | "transcribe"
    | "learn"
    | "summary"
    | "taskReview"
    | "share";

export type PhaseState =
    | "pending"
    | "waiting"
    | "running"
    | "done"
    | "skipped"
    | "failed"
    | "not_processed";

export interface ContentRevisionInput {
    contentId: string;
    contentSourceId: string;
    contentRevision: number;
}

export type SummaryStepName = "summary" | "topics" | "title";

export interface PhaseStepRecord {
    contentId: string;
    contentRevision: number;
    generation: number;
    profileRevisionId?: string;
}

export interface PhaseRecord {
    state: PhaseState;
    reason?: string;
    generation: number;
    inputs?: ContentRevisionInput;
    at: string;
    steps?: Partial<Record<SummaryStepName, PhaseStepRecord>>;
    profileRevisionId?: string;
}

export type PipelinePhases = Partial<Record<PhaseName, PhaseRecord>>;

export interface PipelineProfileFacts {
    revisionId: string;
    automatic: {
        learn: boolean;
        summary: boolean;
        title: boolean;
        topics: boolean;
    };
}

export type PipelineProfileResolution =
    | "resolved"
    | "choose"
    | "waiting_for_curator";

export interface PipelineFacts {
    item: {
        exists: boolean;
        deleted: boolean;
        kind: "audio" | "mail";
        ownerUserId: string;
    };
    view: PipelineView;
    generation: number;
    content: (ContentRevisionInput & { timed: boolean }) | null;
    summaryDueAt: string | null;
    profile: PipelineProfileFacts | null;
    categorization: {
        placementFolderIds: string[];
        intendedFolderIds: string[];
        profileAssigned: boolean;
        resolution: PipelineProfileResolution | null;
    };
    hasEnhancementCredential: boolean;
    mail: {
        autoGenerated: boolean;
        unreadable: boolean;
        shared: boolean;
    } | null;
    summary: {
        exists: boolean;
        stale: boolean;
        jobActive: boolean;
    };
    taskReview: {
        proposals: number;
        followUps: number;
    };
    phases: PipelinePhases;
    at: string;
}

export type PipelineAction =
    | {
          type: "queueSummary";
          presetId: string | null;
          strict: boolean;
      }
    | { type: "queueTopics"; strict: boolean }
    | { type: "queueTitleJob" }
    | { type: "startAutoLearnMail" }
    | { type: "markPhase"; phase: PhaseName; record: PhaseRecord };

export interface PipelinePlan {
    actions: PipelineAction[];
    reason?: "gone";
}
