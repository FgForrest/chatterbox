// @vitest-environment jsdom

import { cleanup, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { MailDetailPane } from "@/components/mail/mail-detail-pane";
import type { Recording } from "@/types/recording";

vi.mock("next/navigation", () => ({
    useSearchParams: () => new URLSearchParams(),
}));

vi.mock("next-intl", () => ({
    useExtracted: () => (message: string) => message,
    useLocale: () => "en",
}));

vi.mock("@/components/confirm-dialog", () => ({
    useConfirm: () => vi.fn().mockResolvedValue(true),
}));

vi.mock("@/components/mail/mail-summary-card", () => ({
    MailSummaryCard: ({ canChange }: { canChange: boolean }) => (
        <div data-testid="mail-summary">
            {canChange && <button type="button">Summarize</button>}
            {canChange && <button type="button">Re-match tasks</button>}
        </div>
    ),
}));

vi.mock("@/components/mail/mail-learn-card", () => ({
    MailLearnCard: ({ canChange }: { canChange: boolean }) => (
        <div data-testid="mail-learn">
            {canChange && <button type="button">Learn</button>}
        </div>
    ),
}));

vi.mock("@/components/pipeline/item-workflow", () => ({
    ItemWorkflow: () => (
        <>
            <div data-testid="workflow-strip" />
            <div data-testid="folder-row" />
        </>
    ),
}));

const mail: Recording = {
    id: "mail-1",
    filename: "Project update",
    duration: 0,
    filesize: 512,
    startTime: "2026-10-16T10:00:00.000Z",
    deviceSn: "mail",
    kind: "mail",
};

beforeEach(() => {
    vi.stubGlobal(
        "fetch",
        vi.fn().mockResolvedValue({
            ok: true,
            json: async () => ({
                id: mail.id,
                isOwn: true,
                ownerName: null,
                subject: mail.filename,
                occurredAt: mail.startTime,
                sentAt: mail.startTime,
                receivedAt: mail.startTime,
                sizeBytes: mail.filesize,
                senderVerified: true,
                autoGenerated: false,
                unreadable: false,
                hasRaw: true,
                rawReapedAt: null,
                contentReapedAt: null,
                summaryReapedAt: null,
                participants: [],
                segments: [
                    {
                        index: 0,
                        role: "body",
                        depth: 0,
                        text: "The message body",
                        participantRef: null,
                        at: null,
                    },
                ],
                attachments: [],
                auth: null,
                pendingShares: [],
                folderIds: [],
                processing: null,
            }),
        }),
    );
});

afterEach(() => {
    cleanup();
    vi.unstubAllGlobals();
});

describe("mail detail layout", () => {
    it("orders the title, workflow, folder row, metadata, and detail cards", async () => {
        const { container } = render(
            <MailDetailPane
                mail={mail}
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        await waitFor(() =>
            expect(screen.getByTestId("workflow-strip")).toBeTruthy(),
        );
        const ordered = [
            screen.getByRole("heading", {
                level: 1,
                name: "Project update",
            }),
            screen.getByTestId("workflow-strip"),
            screen.getByTestId("folder-row"),
            screen.getByText("From"),
            screen.getByRole("heading", { name: "Message" }),
            screen.getByTestId("mail-learn"),
            screen.getByTestId("mail-summary"),
        ];
        for (let index = 1; index < ordered.length; index += 1) {
            expect(
                ordered[index - 1].compareDocumentPosition(ordered[index]) &
                    Node.DOCUMENT_POSITION_FOLLOWING,
            ).toBeTruthy();
        }
        expect(
            screen.getByText("From").closest('[data-slot="card"]'),
        ).toBeNull();
        expect(
            screen.getByRole("heading", { name: "Message" }).closest("header")
                ?.textContent,
        ).toContain("Show formatted");
        expect(container.firstElementChild?.className).toContain("space-y-6");
        expect(
            screen
                .getByRole("button", { name: "Show formatted" })
                .getAttribute("aria-pressed"),
        ).toBe("false");
        expect(
            screen
                .getByRole("link", { name: "Download the message" })
                .getAttribute("title"),
        ).toBe("Download the message");
        expect(
            screen
                .getByRole("button", { name: "Delete" })
                .getAttribute("title"),
        ).toBe("Delete");
    });

    it("renders the folder row before the mail detail loads", () => {
        vi.stubGlobal(
            "fetch",
            vi.fn(() => new Promise<Response>(() => {})),
        );

        render(
            <MailDetailPane
                mail={mail}
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        expect(screen.getByTestId("folder-row")).toBeTruthy();
        expect(screen.getByText("Loading…")).toBeTruthy();
    });

    it("keeps a shared mail read-only on its private view", async () => {
        render(
            <MailDetailPane
                mail={mail}
                shared
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        await screen.findByTestId("mail-summary");
        expect(screen.queryByRole("button", { name: "Summarize" })).toBeNull();
        expect(screen.queryByRole("button", { name: "Learn" })).toBeNull();
        expect(
            screen.queryByRole("button", { name: "Re-match tasks" }),
        ).toBeNull();
    });
});
