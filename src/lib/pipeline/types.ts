import type { ShareGateProblem } from "@/lib/sharing/share-gate";

export type PipelineView = "private" | "org";

export type PhaseName =
    | "categorize"
    | "transcribe"
    | "learn"
    | "summary"
    | "taskReview"
    | "share";

export type PhaseState =
    | "pending"
    | "waiting"
    | "running"
    | "done"
    | "skipped"
    | "failed"
    | "outdated"
    | "not_processed";

export interface ContentRevisionInput {
    contentId: string;
    contentSourceId: string;
    contentRevision: number;
}

export type SummaryStepName = "summary" | "topics" | "title";

export interface PhaseStepRecord {
    contentId: string;
    contentSourceId?: string;
    contentRevision: number;
    generation: number;
    profileRevisionId?: string;
    state?: PhaseState;
    reason?: string;
    sourceFingerprint?: string;
}

export interface PhaseRecord {
    state: PhaseState;
    reason?: string;
    /** Identifies Transcribe failures owned by automatic pipeline processing. */
    automatic?: boolean;
    generation: number;
    inputs?: ContentRevisionInput;
    at: string;
    steps?: Partial<Record<SummaryStepName, PhaseStepRecord>>;
    profileRevisionId?: string;
    problems?: ShareGateProblem[];
}

export type PipelinePhases = Partial<Record<PhaseName, PhaseRecord>>;

export interface PipelineProfileFacts {
    revisionId: string;
    tasksEnabled?: boolean;
    learn?: {
        automatic: boolean;
    };
    transcribe?: {
        automatic: boolean;
        plaudTranscript: "use" | "also_transcribe";
    };
    automatic: {
        learn: boolean;
        summary: boolean;
        title: boolean;
        topics: boolean;
    };
}

export type PipelineProfileResolution =
    | "resolved"
    | "choose"
    | "waiting_for_curator";

export interface PipelineFacts {
    item: {
        exists: boolean;
        deleted: boolean;
        kind: "audio" | "mail";
        ownerUserId: string;
    };
    view: PipelineView;
    generation: number;
    manualOnly?: boolean;
    legacyFallback?: boolean;
    legacyContinuation?: boolean;
    profileUnavailable?: boolean;
    content: (ContentRevisionInput & { timed: boolean }) | null;
    transcription?: {
        riffado: (ContentRevisionInput & { timed: boolean }) | null;
        plaud: (ContentRevisionInput & { timed: boolean }) | null;
        jobActive: boolean;
        contentReaped?: boolean;
        audioReaped?: boolean;
        shared?: boolean;
        failed?: {
            errorCode: string;
            completedAt: string;
        };
    };
    summaryDueAt: string | null;
    profile: PipelineProfileFacts | null;
    categorization: {
        placementFolderIds: string[];
        intendedFolderIds: string[];
        profileAssigned: boolean;
        resolution: PipelineProfileResolution | null;
        resolvedProfile?: {
            profileId: string;
            profileRevisionId: string;
            manualOnly: boolean;
        };
    };
    hasEnhancementCredential: boolean;
    stepAvailability?: Partial<
        Record<SummaryStepName, "available" | "no_provider">
    >;
    learnAvailability?: "available" | "hosted" | "no_provider";
    learnRunOpen?: boolean;
    learnRunInFlight?: boolean;
    learnRunReadyForReview?: boolean;
    learnCorrectionInFlight?: boolean;
    plaudTasks?: {
        fingerprint: string;
    };
    mail: {
        autoGenerated: boolean;
        unreadable: boolean;
        shared: boolean;
    } | null;
    summary: {
        exists: boolean;
        stale: boolean;
        jobActive: boolean;
        phaseJobActive?: boolean;
        failed?: Partial<
            Record<SummaryStepName, { errorCode: string; completedAt: string }>
        >;
    };
    taskReview: {
        proposals: number;
        followUps: number;
    };
    share?: {
        problems: ShareGateProblem[];
        confirmationRequired?: boolean;
    };
    phases: PipelinePhases;
    at: string;
}

export type PipelineAction =
    | {
          type: "queueSummary";
          presetId: string | null;
          strict: boolean;
      }
    | {
          type: "queueTranscription";
      }
    | {
          type: "queueTopics";
          strict: boolean;
          source?: "riffado" | "plaud";
      }
    | { type: "queueTitleJob" }
    | {
          type: "startAutoLearn";
          source: "plaud" | "riffado" | "mail";
          input: ContentRevisionInput;
      }
    | { type: "releaseLearnHold" }
    | { type: "releaseLearnTimeout" }
    | { type: "executeShares" }
    | {
          type: "applyPlaudTasks";
          sourceFingerprint: string;
          content: ContentRevisionInput;
          record: PhaseRecord;
      }
    | {
          type: "completeCategorization";
          profileId: string;
          profileRevisionId: string;
          manualOnly: boolean;
      }
    | { type: "markPhase"; phase: PhaseName; record: PhaseRecord };

export interface PipelinePlan {
    actions: PipelineAction[];
    reason?: "gone";
}
