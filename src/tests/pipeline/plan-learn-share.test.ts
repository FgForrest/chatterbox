import { describe, expect, it } from "vitest";
import { planAdvance } from "@/lib/pipeline/plan";
import type {
    PhaseRecord,
    PipelineFacts,
    PipelineProfileFacts,
} from "@/lib/pipeline/types";

const AT = "2026-10-15T12:00:00.000Z";
const INPUT = {
    contentId: "content-1",
    contentSourceId: "riffado",
    contentRevision: 1,
};

function phase(
    state: PhaseRecord["state"],
    reason: string,
    generation = 2,
): PhaseRecord {
    return { state, reason, generation, at: AT };
}

function profile(
    learn: { enabled: boolean; automatic: boolean } = {
        enabled: true,
        automatic: true,
    },
): PipelineProfileFacts {
    return {
        revisionId: "profile-revision-1",
        learn,
        automatic: {
            learn: learn.enabled && learn.automatic,
            summary: true,
            title: false,
            topics: false,
        },
    };
}

function facts(overrides: Partial<PipelineFacts> = {}): PipelineFacts {
    const base = {
        item: {
            exists: true,
            deleted: false,
            kind: "audio" as const,
            ownerUserId: "owner-1",
        },
        view: "private" as const,
        generation: 2,
        content: { ...INPUT, timed: true },
        summaryDueAt: null,
        profile: profile(),
        categorization: {
            placementFolderIds: ["private-folder"],
            intendedFolderIds: [] as string[],
            profileAssigned: true,
            resolution: "resolved" as const,
        },
        hasEnhancementCredential: true,
        learnAvailability: "available" as const,
        learnRunOpen: false,
        mail: null,
        summary: { exists: false, stale: false, jobActive: false },
        taskReview: { proposals: 0, followUps: 0 },
        share: { problems: [] },
        phases: {
            categorize: phase("done", "categorized"),
            transcribe: {
                ...phase("done", "content-available"),
                inputs: INPUT,
            },
        },
        at: AT,
    } satisfies PipelineFacts;
    return {
        ...base,
        ...overrides,
        phases: { ...base.phases, ...overrides.phases },
    };
}

function learnMark(result: ReturnType<typeof planAdvance>) {
    return result.actions.find(
        (action) => action.type === "markPhase" && action.phase === "learn",
    );
}

describe("Learn prerequisite planning", () => {
    it.each([
        {
            reason: "profile_off",
            change: {
                profile: profile({ enabled: false, automatic: false }),
            },
        },
        {
            reason: "hosted",
            change: { learnAvailability: "hosted" as const },
        },
        {
            reason: "no_provider",
            change: { learnAvailability: "no_provider" as const },
        },
        {
            reason: "no_timings",
            change: { content: { ...INPUT, timed: false } },
        },
    ])("skips audio Learn with $reason and proceeds to Summary", ({
        reason,
        change,
    }) => {
        const result = planAdvance(facts(change));

        expect(learnMark(result)).toEqual(
            expect.objectContaining({
                record: expect.objectContaining({ state: "skipped", reason }),
            }),
        );
        expect(result.actions).toContainEqual(
            expect.objectContaining({ type: "queueSummary" }),
        );
    });

    it("marks unreadable mail terminal without planning Learn or Summary", () => {
        const result = planAdvance(
            facts({
                item: { ...facts().item, kind: "mail" },
                content: {
                    contentId: "mail-content-1",
                    contentSourceId: "mail",
                    contentRevision: 1,
                    timed: false,
                },
                mail: {
                    autoGenerated: false,
                    unreadable: true,
                    shared: false,
                },
                phases: {
                    transcribe: phase("skipped", "not-applicable"),
                },
            }),
        );

        expect(result.actions).toEqual([
            expect.objectContaining({
                type: "markPhase",
                phase: "categorize",
                record: expect.objectContaining({
                    state: "not_processed",
                    reason: "unreadable",
                }),
            }),
        ]);
    });

    it("continues to Summary after automatic Learn records a runtime decline", () => {
        const result = planAdvance(
            facts({
                phases: {
                    learn: {
                        ...phase("skipped", "rate_limited"),
                        inputs: INPUT,
                    },
                },
            }),
        );

        expect(result.actions).toContainEqual(
            expect.objectContaining({ type: "queueSummary" }),
        );
        expect(result.actions).not.toContainEqual(
            expect.objectContaining({ type: "startAutoLearn" }),
        );
    });
});

describe("Learn hold and timeout planning", () => {
    it("makes mail wait for Learn and summarizes only after release", () => {
        const mail = facts({
            item: { ...facts().item, kind: "mail" },
            content: {
                contentId: "mail-content-1",
                contentSourceId: "mail",
                contentRevision: 1,
                timed: false,
            },
            mail: { autoGenerated: false, unreadable: false, shared: false },
            summaryDueAt: "2026-10-18T12:00:00.000Z",
            learnRunOpen: true,
            phases: {
                transcribe: phase("skipped", "not-applicable"),
                learn: {
                    ...phase("running", "started"),
                    inputs: {
                        contentId: "mail-content-1",
                        contentSourceId: "mail",
                        contentRevision: 1,
                    },
                },
            },
        });

        const waiting = planAdvance(mail);
        expect(waiting.actions).toEqual([
            expect.objectContaining({
                type: "markPhase",
                phase: "learn",
                record: expect.objectContaining({
                    state: "waiting",
                    reason: "review_pending",
                }),
            }),
        ]);

        const released = {
            ...mail,
            summaryDueAt: null,
            learnRunOpen: false,
            phases: {
                ...mail.phases,
                learn: {
                    ...phase("done", "released", 3),
                    inputs: mail.phases.learn?.inputs,
                },
            },
            generation: 3,
        } satisfies PipelineFacts;
        expect(planAdvance(released).actions).toContainEqual(
            expect.objectContaining({ type: "queueSummary" }),
        );
    });

    it("releases an expired hold, then summarizes while Learn stays waiting", () => {
        const expired = facts({
            summaryDueAt: "2026-10-14T12:00:00.000Z",
            learnRunOpen: true,
            categorization: {
                placementFolderIds: [],
                intendedFolderIds: ["org-folder"],
                profileAssigned: true,
                resolution: "resolved",
            },
            share: {
                problems: [{ kind: "learn_unfinished", runs: 1 }],
            },
            phases: {
                learn: {
                    ...phase("waiting", "review_pending"),
                    inputs: INPUT,
                },
            },
        });
        expect(planAdvance(expired).actions).toEqual([
            { type: "releaseLearnTimeout" },
        ]);

        const timedOut = {
            ...expired,
            summaryDueAt: null,
            generation: 3,
            phases: {
                ...expired.phases,
                learn: {
                    ...phase("waiting", "review_pending_timeout", 3),
                    inputs: INPUT,
                },
            },
        } satisfies PipelineFacts;
        const result = planAdvance(timedOut);
        expect(result.actions).toContainEqual(
            expect.objectContaining({ type: "queueSummary" }),
        );
        expect(result.actions).toContainEqual(
            expect.objectContaining({
                type: "markPhase",
                phase: "share",
                record: expect.objectContaining({ state: "waiting" }),
            }),
        );
        expect(result.actions).not.toContainEqual({ type: "executeShares" });
        expect(timedOut.phases.learn).toMatchObject({
            state: "waiting",
            reason: "review_pending_timeout",
        });
        expect(timedOut.learnRunOpen).toBe(true);
    });

    it("lets Summary proceed during a manual Learn run but gates Share until it closes", () => {
        const open = facts({
            learnRunOpen: true,
            categorization: {
                placementFolderIds: [],
                intendedFolderIds: ["org-folder"],
                profileAssigned: true,
                resolution: "resolved",
            },
            share: {
                problems: [{ kind: "learn_unfinished", runs: 1 }],
            },
        });

        const openPlan = planAdvance(open);
        expect(learnMark(openPlan)).toEqual(
            expect.objectContaining({
                record: expect.objectContaining({
                    state: "running",
                    reason: "manual",
                }),
            }),
        );
        expect(openPlan.actions).toContainEqual(
            expect.objectContaining({ type: "queueSummary" }),
        );
        expect(openPlan.actions).toContainEqual(
            expect.objectContaining({
                type: "markPhase",
                phase: "share",
                record: expect.objectContaining({
                    state: "waiting",
                    reason: "gate_blocked",
                }),
            }),
        );
        expect(openPlan.actions).not.toContainEqual({ type: "executeShares" });

        const closed = facts({
            generation: 3,
            learnRunOpen: false,
            categorization: open.categorization,
            share: { problems: [] },
            summary: { exists: true, stale: false, jobActive: false },
            phases: {
                learn: { ...phase("running", "manual"), inputs: INPUT },
                summary: {
                    ...phase("done", "generated"),
                    inputs: INPUT,
                    steps: {
                        summary: {
                            contentId: INPUT.contentId,
                            contentRevision: INPUT.contentRevision,
                            generation: 2,
                        },
                    },
                },
                share: {
                    ...phase("waiting", "gate_blocked"),
                    problems: [{ kind: "learn_unfinished", runs: 1 }],
                },
            },
        });
        const closedPlan = planAdvance(closed);
        expect(closedPlan.actions).toContainEqual({ type: "executeShares" });
        expect(
            closedPlan.actions.filter(
                (action) => action.type === "executeShares",
            ),
        ).toHaveLength(1);
    });
});

describe("Share planning", () => {
    function shareReady(overrides: Partial<PipelineFacts> = {}) {
        return facts({
            categorization: {
                placementFolderIds: [],
                intendedFolderIds: ["org-folder"],
                profileAssigned: true,
                resolution: "resolved",
            },
            profile: profile({ enabled: false, automatic: false }),
            phases: {
                learn: { ...phase("skipped", "profile_off"), inputs: INPUT },
                summary: {
                    ...phase("done", "generated"),
                    inputs: INPUT,
                    steps: {
                        summary: {
                            contentId: INPUT.contentId,
                            contentRevision: INPUT.contentRevision,
                            generation: 2,
                        },
                    },
                },
            },
            summary: { exists: true, stale: false, jobActive: false },
            ...overrides,
        });
    }

    it("waits with gate problems, then executes and records a completed share", () => {
        const blocked = shareReady({
            share: {
                problems: [{ kind: "tasks_unreviewed", proposals: 2 }],
            },
        });
        expect(planAdvance(blocked).actions).toContainEqual(
            expect.objectContaining({
                type: "markPhase",
                phase: "share",
                record: expect.objectContaining({
                    state: "waiting",
                    reason: "gate_blocked",
                    problems: [{ kind: "tasks_unreviewed", proposals: 2 }],
                }),
            }),
        );

        const passing = shareReady({
            generation: 3,
            phases: {
                ...blocked.phases,
                share: {
                    ...phase("waiting", "gate_blocked"),
                    problems: [{ kind: "tasks_unreviewed", proposals: 2 }],
                },
            },
        });
        expect(planAdvance(passing).actions).toContainEqual({
            type: "executeShares",
        });
    });

    it("keeps a cancelled final intent skipped", () => {
        const cancelled = shareReady({
            categorization: {
                placementFolderIds: [],
                intendedFolderIds: [],
                profileAssigned: true,
                resolution: "resolved",
            },
            phases: {
                learn: { ...phase("skipped", "profile_off", 3), inputs: INPUT },
                summary: {
                    ...phase("done", "generated", 3),
                    inputs: INPUT,
                    steps: {
                        summary: {
                            contentId: INPUT.contentId,
                            contentRevision: INPUT.contentRevision,
                            generation: 3,
                        },
                    },
                },
                share: phase("skipped", "cancelled", 3),
            },
            generation: 3,
        });
        expect(planAdvance(cancelled).actions).toEqual([]);
    });

    it("does not execute Share twice in one generation", () => {
        const ready = shareReady();
        const attempted = shareReady({
            phases: {
                ...ready.phases,
                share: phase("waiting", "org_unavailable"),
            },
        });

        expect(planAdvance(attempted).actions).toEqual([]);
    });
});
