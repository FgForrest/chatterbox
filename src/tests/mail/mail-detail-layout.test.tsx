// @vitest-environment jsdom

import { cleanup, render, screen, waitFor } from "@testing-library/react";
import type { ReactNode } from "react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { MailDetailPane } from "@/components/mail/mail-detail-pane";
import type { ItemProcessingPresentation } from "@/lib/pipeline/presentation";
import type { Recording } from "@/types/recording";

vi.mock("next/navigation", () => ({
    useSearchParams: () => new URLSearchParams(),
}));

vi.mock("next-intl", () => ({
    useExtracted: () => (message: string) => message,
    useLocale: () => "en",
}));

vi.mock("@/components/confirm-dialog", () => ({
    useConfirm: () => vi.fn().mockResolvedValue(true),
}));

vi.mock("@/components/recordings/ai-cost-summary", () => ({
    AiCostSummary: ({ kind }: { kind: "audio" | "mail" }) => (
        <span>
            {kind === "mail"
                ? "No AI spend tracked for this mail"
                : "No AI spend tracked for this recording"}
        </span>
    ),
}));

vi.mock("@/components/ui/tooltip", () => ({
    Tooltip: ({ children }: { children: ReactNode }) => children,
    TooltipTrigger: ({ children }: { children: ReactNode }) => children,
    TooltipContent: ({ children }: { children: ReactNode }) => children,
}));

vi.mock("@/components/mail/mail-summary-card", () => ({
    MailSummaryCard: ({ canChange }: { canChange: boolean }) => (
        <div data-testid="mail-summary">
            {canChange && <button type="button">Summarize</button>}
            {canChange && <button type="button">Re-match tasks</button>}
        </div>
    ),
}));

vi.mock("@/components/mail/mail-learn-card", () => ({
    MailLearnCard: ({ canChange }: { canChange: boolean }) => (
        <div data-testid="mail-learn">
            {canChange && <button type="button">Learn</button>}
        </div>
    ),
}));

vi.mock("@/components/pipeline/item-workflow", () => ({
    ItemWorkflow: ({
        initialData,
    }: {
        initialData?: ItemProcessingPresentation | null;
    }) => (
        <>
            <div data-testid="workflow-strip" />
            <div data-testid="folder-row" />
            {initialData?.intents.map((intent) => (
                <span key={intent.folderId}>
                    {intent.path}
                    {intent.confirmationRequired && !intent.confirmed && (
                        <button type="button">Share now</button>
                    )}
                    <button
                        type="button"
                        aria-label={`Cancel ${intent.path}`}
                    />
                </span>
            ))}
        </>
    ),
}));

const mail: Recording = {
    id: "mail-1",
    filename: "Project update",
    duration: 0,
    filesize: 512,
    startTime: "2026-10-16T10:00:00.000Z",
    deviceSn: "mail",
    kind: "mail",
    mail: {
        from: "Alice <alice@example.test>",
        senderVerified: true,
        hasAttachments: false,
        waitingToShare: false,
        autoGenerated: false,
    },
};

beforeEach(() => {
    vi.stubGlobal(
        "fetch",
        vi.fn().mockResolvedValue({
            ok: true,
            json: async () => ({
                id: mail.id,
                isOwn: true,
                ownerName: null,
                subject: mail.filename,
                occurredAt: mail.startTime,
                sentAt: mail.startTime,
                receivedAt: mail.startTime,
                sizeBytes: mail.filesize,
                senderVerified: true,
                autoGenerated: false,
                unreadable: false,
                hasRaw: true,
                rawReapedAt: null,
                contentReapedAt: null,
                summaryReapedAt: null,
                participants: [],
                segments: [
                    {
                        index: 0,
                        role: "body",
                        depth: 0,
                        text: "The message body",
                        participantRef: null,
                        at: null,
                    },
                ],
                attachments: [],
                auth: null,
                folderIds: [],
                processing: null,
            }),
        }),
    );
});

afterEach(() => {
    cleanup();
    vi.unstubAllGlobals();
});

describe("mail detail layout", () => {
    it("orders the title, workflow, folder row, metadata, and detail cards", async () => {
        const { container } = render(
            <MailDetailPane
                mail={mail}
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        await waitFor(() =>
            expect(screen.getByTestId("workflow-strip")).toBeTruthy(),
        );
        const ordered = [
            screen.getByRole("heading", {
                level: 1,
                name: "Project update",
            }),
            screen.getByTestId("workflow-strip"),
            screen.getByTestId("folder-row"),
            screen.getByText("From"),
            screen.getByRole("heading", { name: "Message" }),
            screen.getByTestId("mail-learn"),
            screen.getByTestId("mail-summary"),
        ];
        for (let index = 1; index < ordered.length; index += 1) {
            expect(
                ordered[index - 1].compareDocumentPosition(ordered[index]) &
                    Node.DOCUMENT_POSITION_FOLLOWING,
            ).toBeTruthy();
        }
        expect(
            screen.getByText("From").closest('[data-slot="card"]'),
        ).toBeNull();
        expect(
            screen.getByRole("heading", { name: "Message" }).closest("header")
                ?.textContent,
        ).toContain("Show formatted");
        expect(container.firstElementChild?.className).toContain("space-y-6");
        expect(
            screen
                .getByRole("button", { name: "Show formatted" })
                .getAttribute("aria-pressed"),
        ).toBe("false");
        expect(
            screen
                .getByRole("link", { name: "Download the message" })
                .closest("header")?.textContent,
        ).toContain("Message");
        expect(
            screen.getByRole("button", { name: "Erase mail artifacts" }),
        ).toBeTruthy();
        expect(
            screen.getByRole("button", { name: "Rename {name}" }),
        ).toBeTruthy();
        expect(
            screen.getByRole("button", {
                name: "Regenerate title for {name}",
            }),
        ).toBeTruthy();
        expect(screen.getByText("Alice <alice@example.test>")).toBeTruthy();
        expect(screen.getByText("512 B")).toBeTruthy();
        expect(
            screen.getByText("No AI spend tracked for this mail"),
        ).toBeTruthy();
    });

    it("renders the folder row before the mail detail loads", () => {
        vi.stubGlobal(
            "fetch",
            vi.fn(() => new Promise<Response>(() => {})),
        );

        render(
            <MailDetailPane
                mail={mail}
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        expect(screen.getByTestId("folder-row")).toBeTruthy();
        expect(screen.getByText("Loading…")).toBeTruthy();
    });

    it("shows a pending share only through the shared intent chip", async () => {
        const processing: ItemProcessingPresentation = {
            itemId: mail.id,
            kind: "mail",
            legacy: false,
            manualOnly: true,
            phases: {},
            profile: null,
            placements: [],
            intents: [
                {
                    folderId: "team",
                    name: "Team",
                    path: "Organization › Team",
                    confirmationRequired: true,
                    confirmed: false,
                },
            ],
            outputs: { transcript: false, learn: false, summary: false },
            processAgain: false,
            processAgainReason: null,
            learnFindingsWaiting: 0,
            taskReviewWaiting: 0,
            jobs: { transcription: null, summary: null },
            failures: [],
        };
        vi.stubGlobal(
            "fetch",
            vi.fn().mockResolvedValue({
                ok: true,
                json: async () => ({
                    id: mail.id,
                    isOwn: true,
                    ownerName: null,
                    subject: mail.filename,
                    occurredAt: mail.startTime,
                    sentAt: mail.startTime,
                    receivedAt: mail.startTime,
                    sizeBytes: mail.filesize,
                    senderVerified: true,
                    autoGenerated: false,
                    unreadable: false,
                    hasRaw: true,
                    rawReapedAt: null,
                    contentReapedAt: null,
                    summaryReapedAt: null,
                    participants: [],
                    segments: [],
                    attachments: [],
                    auth: null,
                    folderIds: [],
                    processing,
                }),
            }),
        );

        render(
            <MailDetailPane
                mail={mail}
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        expect(await screen.findByText("Organization › Team")).toBeTruthy();
        expect(
            screen.getAllByRole("button", { name: "Share now" }),
        ).toHaveLength(1);
        expect(
            screen.getByRole("button", {
                name: "Cancel Organization › Team",
            }),
        ).toBeTruthy();
        expect(screen.queryByText(/waiting for your review/)).toBeNull();
        expect(
            screen.queryByRole("button", { name: "Keep private" }),
        ).toBeNull();
    });

    it("describes erased mail artifacts without attributing them to retention", async () => {
        vi.stubGlobal(
            "fetch",
            vi.fn().mockResolvedValue({
                ok: true,
                json: async () => ({
                    id: mail.id,
                    isOwn: true,
                    ownerName: null,
                    subject: mail.filename,
                    occurredAt: mail.startTime,
                    sentAt: mail.startTime,
                    receivedAt: mail.startTime,
                    sizeBytes: mail.filesize,
                    senderVerified: true,
                    autoGenerated: false,
                    unreadable: false,
                    hasRaw: false,
                    rawReapedAt: "2026-10-18T13:00:00.000Z",
                    contentReapedAt: "2026-10-18T13:01:00.000Z",
                    summaryReapedAt: "2026-10-18T13:02:00.000Z",
                    participants: [],
                    segments: [],
                    attachments: [],
                    auth: null,
                    folderIds: [],
                    processing: null,
                }),
            }),
        );

        render(
            <MailDetailPane
                mail={mail}
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        expect(
            await screen.findByText(
                "The message as it arrived and its attachments were removed on {date}.",
            ),
        ).toBeTruthy();
        expect(
            screen.getByText("Its text was removed on {date}."),
        ).toBeTruthy();
        expect(
            screen.getByText("Its summary was removed on {date}."),
        ).toBeTruthy();
        expect(screen.queryByText(/Retention removed/)).toBeNull();
    });

    it("keeps a shared mail read-only on its private view", async () => {
        render(
            <MailDetailPane
                mail={mail}
                shared
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        await screen.findByTestId("mail-summary");
        expect(screen.queryByRole("button", { name: "Summarize" })).toBeNull();
        expect(screen.queryByRole("button", { name: "Learn" })).toBeNull();
        expect(
            screen.queryByRole("button", { name: "Re-match tasks" }),
        ).toBeNull();
        expect(
            screen.queryByRole("button", { name: "Rename {name}" }),
        ).toBeNull();
    });

    it("uses the shared Organization marker without Organization view text", async () => {
        render(
            <MailDetailPane
                mail={{
                    ...mail,
                    view: "org",
                    isOwn: false,
                    ownerName: "Eva",
                }}
                dateTimeFormat="absolute"
                onBackToList={vi.fn()}
                hiddenOnMobile={false}
                onChanged={vi.fn()}
                folders={[]}
                folderAssignments={[]}
                onSelectFolder={vi.fn()}
                onAddToFolder={vi.fn()}
                onRemoveFromFolder={vi.fn()}
                onMoveBetweenFolders={vi.fn()}
            />,
        );

        await screen.findByTestId("mail-summary");
        expect(screen.getByLabelText("Organization")).toBeTruthy();
        expect(screen.getByText("Shared by {owner}")).toBeTruthy();
        expect(screen.queryByText("Organization view")).toBeNull();
        expect(
            screen.queryByRole("link", { name: "Download the message" }),
        ).toBeNull();
    });
});
