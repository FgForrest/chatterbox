// @vitest-environment jsdom

import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { ConfirmDialogProvider } from "@/components/confirm-dialog";
import { FolderRecordingPane } from "@/components/dashboard/folder-recording-pane";
import { TooltipProvider } from "@/components/ui/tooltip";
import type { RecordingFolder } from "@/types/folder";
import type { Recording } from "@/types/recording";

const privateRoot: RecordingFolder = {
    id: "private",
    parentId: null,
    name: "Private",
    kind: "private",
    sortOrder: 0,
    scope: "personal",
    version: 0,
};
const meetings: RecordingFolder = {
    id: "meetings",
    parentId: "private",
    name: "Meetings",
    kind: "custom",
    sortOrder: 0,
    scope: "personal",
    version: 0,
};
const planning: RecordingFolder = {
    id: "planning",
    parentId: "meetings",
    name: "Planning",
    kind: "custom",
    sortOrder: 0,
    scope: "personal",
    version: 0,
};
const orgRoot: RecordingFolder = {
    id: "org-root",
    parentId: null,
    name: "Organization",
    kind: "public",
    sortOrder: 0,
    scope: "org",
    version: 0,
};
const orgPlanning: RecordingFolder = {
    ...planning,
    id: "org-planning",
    parentId: orgRoot.id,
    name: "Organization planning",
    scope: "org",
};
const recordings: Recording[] = [
    {
        id: "rec-direct",
        filename: "Direct meeting",
        duration: 60_000,
        filesize: 1000,
        startTime: new Date(0).toISOString(),
        deviceSn: "local",
    },
    {
        id: "rec-child",
        filename: "Child meeting",
        duration: 120_000,
        filesize: 2000,
        startTime: new Date(1).toISOString(),
        deviceSn: "local",
    },
    {
        id: "mail-direct",
        kind: "mail",
        filename: "Direct mail",
        duration: 0,
        filesize: 500,
        startTime: new Date(2).toISOString(),
        deviceSn: "mail",
        mail: {
            from: "sender@example.com",
            senderVerified: true,
            hasAttachments: false,
            waitingToShare: false,
            autoGenerated: false,
        },
    },
];

function renderPane(folder: RecordingFolder, canCurate = false) {
    render(
        <TooltipProvider>
            <ConfirmDialogProvider>
                <FolderRecordingPane
                    folder={folder}
                    folders={[
                        privateRoot,
                        meetings,
                        planning,
                        orgRoot,
                        orgPlanning,
                    ]}
                    assignments={[
                        { recordingId: "rec-direct", folderId: "meetings" },
                        { recordingId: "rec-child", folderId: "planning" },
                        { recordingId: "mail-direct", folderId: "meetings" },
                        { recordingId: "rec-direct", folderId: "org-planning" },
                        {
                            recordingId: "mail-direct",
                            folderId: "org-planning",
                        },
                    ]}
                    recordings={recordings}
                    dateTimeFormat="relative"
                    onSelectRecording={vi.fn()}
                    onRenameFolder={vi.fn()}
                    onDeleteFolder={vi.fn()}
                    hiddenOnMobile={false}
                    onBackToFolders={vi.fn()}
                    exportProviders={{
                        filesystem: false,
                        googleDrive: false,
                        mail: false,
                    }}
                    isOrgAccount={folder.scope === "org"}
                    mailEnabled
                    canCurate={canCurate}
                />
            </ConfirmDialogProvider>
        </TooltipProvider>,
    );
}

describe("folder recording pane", () => {
    beforeEach(() => {
        vi.stubGlobal(
            "fetch",
            vi.fn().mockResolvedValue(
                Response.json({
                    writable: true,
                    addresses: [
                        {
                            id: "current",
                            kind: "folder",
                            address: "weekly@example.com",
                            label: null,
                            primary: true,
                            folderId: "folder",
                            baseAddressId: null,
                            lastReceivedAt: "2026-10-16T10:00:00.000Z",
                            createdAt: "2026-10-16T09:00:00.000Z",
                        },
                    ],
                }),
            ),
        );
    });

    afterEach(() => {
        cleanup();
        vi.unstubAllGlobals();
    });

    it("includes recordings assigned to descendant folders", () => {
        renderPane(meetings);
        expect(screen.getByText("Direct meeting")).toBeTruthy();
        expect(screen.getByText("Child meeting")).toBeTruthy();
        expect(screen.getByText("3 items")).toBeTruthy();
    });

    it("lists every recording in the Private root", () => {
        renderPane(privateRoot);
        expect(screen.getByText("Direct meeting")).toBeTruthy();
        expect(screen.getByText("Child meeting")).toBeTruthy();
        expect(screen.getByText("3 items")).toBeTruthy();
        expect(screen.getAllByText("Meetings")).toHaveLength(2);
        expect(screen.getByText("Planning")).toBeTruthy();
    });

    it("makes recording titles draggable as folder assignments", () => {
        renderPane(privateRoot);
        const dataTransfer = {
            effectAllowed: "none",
            setData: vi.fn(),
        };

        fireEvent.dragStart(
            screen.getByRole("button", { name: "Open Direct meeting" }),
            { dataTransfer },
        );

        expect(dataTransfer.setData).toHaveBeenCalledWith(
            "application/x-riffado-recording",
            "rec-direct",
        );
        expect(dataTransfer.effectAllowed).toBe("copy");
    });

    it("always renders export and hides synchronization without an applicable export", () => {
        renderPane(meetings);
        expect(screen.getByRole("button", { name: "Export" })).toBeTruthy();
        expect(screen.getByRole("button", { name: "Processing" })).toBeTruthy();
        expect(
            screen.queryByRole("button", { name: "Synchronize" }),
        ).toBeNull();
    });

    it("hides Organization curation controls from members", () => {
        renderPane(orgPlanning);

        expect(screen.queryByRole("button", { name: "Processing" })).toBeNull();
        expect(screen.getByRole("button", { name: "Export" })).toBeTruthy();
        expect(screen.queryByRole("button", { name: "Rename" })).toBeNull();
        expect(screen.queryByRole("button", { name: "Delete" })).toBeNull();
    });

    it("shows Organization curation controls to curators", () => {
        renderPane(orgPlanning, true);

        expect(screen.getByRole("button", { name: "Processing" })).toBeTruthy();
        expect(screen.getByRole("button", { name: "Rename" })).toBeTruthy();
        expect(screen.getByRole("button", { name: "Delete" })).toBeTruthy();
    });

    describe.each([
        {
            label: "personal",
            folder: meetings,
            canCurate: false,
            path: "Private/Meetings·3 items",
            count: "3 items",
        },
        {
            label: "Organization",
            folder: orgPlanning,
            canCurate: true,
            path: "Organization/Organization planning·2 items",
            count: "2 items",
        },
    ])("$label folder header", ({ folder, canCurate, path, count }) => {
        it("shows the item count, address, and permitted actions", async () => {
            renderPane(folder, canCurate);

            expect(screen.getByText(count).parentElement?.textContent).toBe(
                path,
            );
            expect(await screen.findByText("weekly@example.com")).toBeTruthy();
            expect(screen.queryByText(/last mail/)).toBeNull();
            for (const action of ["Processing", "Export", "Rename", "Delete"]) {
                expect(
                    screen.getByRole("button", { name: action }),
                ).toBeTruthy();
            }
        });
    });

    it("uses the recording action badge for a mail row", () => {
        renderPane(meetings);
        const row = screen.getByRole("button", { name: "Open Direct mail" });
        expect(row.firstElementChild?.className).toContain("bg-primary");
        expect(row.querySelector("svg")).toBeTruthy();
    });

    it("sorts the recording table by every displayed column", () => {
        renderPane(privateRoot);

        expect(
            screen.getByRole("button", { name: "Sort by Title" }),
        ).toBeTruthy();
        expect(
            screen.getByRole("button", {
                name: "Sort by Date, descending",
            }),
        ).toBeTruthy();
        expect(
            screen.getByRole("button", { name: "Sort by Duration" }),
        ).toBeTruthy();
        expect(
            screen.getByRole("button", { name: "Sort by Size" }),
        ).toBeTruthy();

        fireEvent.click(screen.getByRole("button", { name: "Sort by Title" }));
        fireEvent.click(
            screen.getByRole("button", {
                name: "Sort by Title, ascending",
            }),
        );
        const rows = screen.getAllByRole("button", { name: /^Open / });
        expect(rows.map((row) => row.getAttribute("aria-label"))).toEqual([
            "Open Direct meeting",
            "Open Direct mail",
            "Open Child meeting",
        ]);
    });
});
