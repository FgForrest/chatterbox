/** How long the title, summary and topics wait for Learn's review. */
export const AUTO_LEARN_HOLD_MS = 72 * 60 * 60 * 1000;

export const LEARN_RELEASE_JOB_KIND = "learn.release";

export type AutoLearnSkipReason =
    | "profile_off"
    | "hosted"
    | "no_provider"
    | "no_timings"
    | "unreadable"
    | "rate_limited"
    | "gone"
    | "shared"
    | "start_failed";

export type AutoLearnOutcome =
    | { status: "started" }
    | { status: "deferred"; delayMs: number }
    | { status: "skipped"; reason: AutoLearnSkipReason };

/** Start automatic Learn and establish its three-day Summary hold. */
export async function startAutomaticLearn(input: {
    userId: string;
    itemId: string;
    source: "plaud" | "riffado" | "mail";
    timed?: boolean;
}): Promise<AutoLearnOutcome> {
    const { userId, itemId, source } = input;
    try {
        if (source !== "mail" && !input.timed) {
            return { status: "skipped", reason: "no_timings" };
        }
        if (!isLearnDeploymentAvailable()) {
            return { status: "skipped", reason: "hosted" };
        }
        const profile = await resolveItemProfile(itemId, "private", userId);
        const learn = profile.settings.steps.learn;
        const [processing] = await db
            .select({ manualOnly: itemProcessing.manualOnly })
            .from(itemProcessing)
            .where(
                and(
                    eq(itemProcessing.itemId, itemId),
                    eq(itemProcessing.userId, userId),
                    eq(itemProcessing.view, "private"),
                ),
            )
            .limit(1);
        if (processing?.manualOnly || !learn.automatic) {
            return { status: "skipped", reason: "profile_off" };
        }
        try {
            await resolveStepProvider({
                step: "learn",
                pin: learn.provider,
                actorUserId: userId,
            });
        } catch {
            return { status: "skipped", reason: "no_provider" };
        }
        if (source === "mail") {
            const [mail] = await db
                .select({
                    autoGenerated: mailMessages.autoGenerated,
                    unreadable: mailMessages.unreadable,
                })
                .from(mailMessages)
                .where(
                    and(
                        eq(mailMessages.id, itemId),
                        eq(mailMessages.userId, userId),
                    ),
                )
                .limit(1);
            if (!mail || mail.autoGenerated || mail.unreadable) {
                return { status: "skipped", reason: "unreadable" };
            }
        }
        const access = await resolveRecordingAccess(userId, itemId, {
            kinds: ALL_ITEM_KINDS,
        });
        if (!access || access.role !== "owner") {
            return { status: "skipped", reason: "gone" };
        }
        const rateLimit = await consumeRateLimitBucket(
            `auto-learn:user:${userId}`,
            {
                limit: env.AUTO_SUMMARY_RATE_LIMIT_PER_HOUR,
                windowMs: 60 * 60 * 1000,
            },
        );
        if (!rateLimit.allowed) {
            return {
                status: "deferred",
                delayMs: Math.max(
                    1_000,
                    rateLimit.resetAt.getTime() - Date.now(),
                ),
            };
        }

        try {
            await startLearnRun({
                access: {
                    ...access,
                    view: access.shared ? "org" : "private",
                    contentUserId: userId,
                },
                actorUserId: userId,
                source: source === "mail" ? "riffado" : source,
                trigger: "auto",
            });
        } catch (error) {
            console.error(
                `Automatic Learn could not start for item ${itemId}:`,
                error,
            );
            return { status: "skipped", reason: "start_failed" };
        }
        const [held] = await db
            .update(chatterItems)
            .set({ summaryDueAt: new Date(Date.now() + AUTO_LEARN_HOLD_MS) })
            .where(
                and(
                    eq(chatterItems.id, itemId),
                    eq(chatterItems.userId, userId),
                    isNull(chatterItems.deletedAt),
                ),
            )
            .returning({ id: chatterItems.id });
        if (!held) return { status: "skipped", reason: "gone" };
        await releaseAutoLearnHold(itemId);
        return { status: "started" };
    } catch (error) {
        console.error(`Automatic Learn skipped for item ${itemId}:`, error);
        return { status: "skipped", reason: "start_failed" };
    }
}

/**
 * A correction pass on the recording still to run: a job
 * queued or running, other than `exceptJobId` (the pass that asks).
 */
function correctionPending(
    recordingId: string | typeof chatterItems.id,
    exceptJobId?: string,
) {
    return db
        .select({ id: asyncJobs.id })
        .from(asyncJobs)
        .where(
            and(
                eq(asyncJobs.kind, LEARN_CORRECT_JOB_KIND),
                or(
                    eq(asyncJobs.subjectId, recordingId),
                    eq(
                        asyncJobs.subjectId,
                        typeof recordingId === "string"
                            ? recordingJobSubject(recordingId, "org")
                            : sql`'org:' || ${recordingId}`,
                    ),
                ),
                inArray(asyncJobs.status, ["pending", "processing"]),
                exceptJobId ? ne(asyncJobs.id, exceptJobId) : undefined,
            ),
        );
}

/**
 * Release a recording's hold when no run in its current scope is open and
 * no correction pass is still to run (`expired`: when its time is up,
 * whatever is open). Exactly once: the hold is cleared by the statement
 * that checks it, and the pipeline driver is requested in the same transaction.
 * Returns whether it released. Never throws.
 */
export async function releaseAutoLearnHold(
    recordingId: string,
    {
        expired = false,
        now = new Date(),
        exceptJobId,
    }: {
        expired?: boolean;
        now?: Date;
        /** The correction pass releasing it, still running as it asks. */
        exceptJobId?: string;
    } = {},
): Promise<boolean> {
    try {
        if (!expired) await settleDeadLearnRuns(recordingId);
        const orgUserId = await getOrgUserId();
        const open = db
            .select({ id: learnRuns.id })
            .from(learnRuns)
            .where(
                and(
                    eq(learnRuns.itemId, recordingId),
                    eq(learnRuns.userId, chatterItems.userId),
                    learnRunCurrentScope(orgUserId),
                    learnRunOpen(),
                ),
            );
        const released = await db.transaction(async (tx) => {
            const [row] = await tx
                .update(chatterItems)
                .set({ summaryDueAt: null })
                .where(
                    and(
                        eq(chatterItems.id, recordingId),
                        isNotNull(chatterItems.summaryDueAt),
                        // A renewed hold is not the one whose time was up.
                        expired
                            ? lte(chatterItems.summaryDueAt, now)
                            : and(
                                  notExists(open),
                                  notExists(
                                      learnScopeRestartPending(recordingId),
                                  ),
                                  notExists(
                                      correctionPending(
                                          recordingId,
                                          exceptJobId,
                                      ),
                                  ),
                              ),
                    ),
                )
                .returning({ userId: chatterItems.userId });
            if (!row) return false;
            await requestLearnReleaseInTx(tx, recordingId, row.userId, expired);
            return true;
        });
        if (released) nudge();
        return released;
    } catch (error) {
        console.error(
            `Could not release what waited for Learn on recording ${recordingId}:`,
            error,
        );
        return false;
    }
}

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

async function requestLearnReleaseInTx(
    tx: Tx,
    recordingId: string,
    userId: string,
    timedOut = false,
): Promise<Awaited<ReturnType<typeof requestAdvanceInTx>>> {
    const requested = await requestAdvanceInTx(tx, {
        itemId: recordingId,
        userId,
        view: "private",
        reason: "learn-released",
    });
    if (!requested) return null;

    await markLearnReleasedInTx(tx, {
        itemId: recordingId,
        userId,
        generation: requested.requestedGeneration,
        timedOut,
    });
    return requested;
}

export interface LearnReleasePayload {
    recordingId: string;
}

/**
 * Only drains `learn.release` jobs queued before the processing pipeline
 * deployed. Remove this delegate one release after that deployment.
 */
export const learnReleaseJobHandler: JobHandler<LearnReleasePayload> = {
    kind: LEARN_RELEASE_JOB_KIND,
    concurrency: 2,
    maxAttempts: 5,
    timeoutMs: 60_000,
    backoff: { baseMs: 10_000, maxMs: 5 * 60_000, jitter: 0.3 },
    parsePayload(raw) {
        if (typeof raw.recordingId !== "string" || !raw.recordingId) {
            throw new InvalidJobPayloadError(
                LEARN_RELEASE_JOB_KIND,
                "recordingId",
            );
        }
        return { recordingId: raw.recordingId };
    },
    async run({ userId, payload }): Promise<JobResult> {
        const requested = await db.transaction((tx) =>
            requestLearnReleaseInTx(tx, payload.recordingId, userId),
        );
        if (!requested) return { skipped: "gone" };
        nudge();
        return { queued: ["pipeline.advance"] };
    },
};

/**
 * Release the holds whose time is up, and those nothing holds any more (a
 * run whose job died is settled first: its hold would otherwise wait out
 * the 72 h), a batch at a time. Only those: holds still waiting for their
 * review are never read, so however many there are, none of them keeps a
 * releasable one out of the batch.
 */
export async function sweepAutoLearnHolds(
    now = new Date(),
    limit = 500,
): Promise<number> {
    const orgUserId = await getOrgUserId();
    const open = db
        .select({ id: learnRuns.id })
        .from(learnRuns)
        .where(
            and(
                eq(learnRuns.itemId, chatterItems.id),
                eq(learnRuns.userId, chatterItems.userId),
                learnRunCurrentScope(orgUserId),
                learnRunOpen(),
            ),
        );
    const held = await db
        .select({ id: chatterItems.id, dueAt: chatterItems.summaryDueAt })
        .from(chatterItems)
        .where(
            and(
                isNotNull(chatterItems.summaryDueAt),
                or(
                    lte(chatterItems.summaryDueAt, now),
                    and(
                        notExists(open),
                        notExists(learnScopeRestartPending(chatterItems.id)),
                        notExists(correctionPending(chatterItems.id)),
                    ),
                ),
            ),
        )
        .orderBy(chatterItems.summaryDueAt)
        .limit(limit);
    let released = 0;
    for (const { id, dueAt } of held) {
        const expired = dueAt !== null && dueAt <= now;
        if (await releaseAutoLearnHold(id, { expired, now })) released++;
    }
    return released;
}

const SWEEP_MS = 5 * 60 * 1000;
let sweeper: ReturnType<typeof setInterval> | undefined;

/** Idempotent. The timeout is in hours; a few minutes late is fine. */
export function startAutoLearnSweeper(): void {
    if (sweeper) return;
    sweeper = setInterval(() => {
        void sweepAutoLearnHolds().catch((error) =>
            console.error("[auto-learn] sweep failed:", error),
        );
    }, SWEEP_MS);
    sweeper.unref?.();
}
