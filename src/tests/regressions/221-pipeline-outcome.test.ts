import { describe, expect, it } from "vitest";
import { outcomeRecord, type StepOutcome } from "@/lib/pipeline/outcome";
import { planAdvance } from "@/lib/pipeline/plan";
import type { ItemProcessingPresentation } from "@/lib/pipeline/presentation";
import type { PipelineFacts } from "@/lib/pipeline/types";
import { deriveWorkflowStatus } from "@/lib/pipeline/workflow-status";
import { processingFixture } from "@/tests/pipeline/processing-fixture";

describe("#221 pipeline outcomes", () => {
    it.each([
        "audio",
        "mail",
    ] as const)("requeues a settled held %s summary after Learn releases without repeating it during review", (kind) => {
        const content = {
            contentId: "content-veln",
            contentSourceId: kind === "audio" ? "riffado" : "mail",
            contentRevision: 1,
        };
        const at = "2026-10-01T00:00:00.000Z";
        const facts: PipelineFacts = {
            item: {
                exists: true,
                deleted: false,
                kind,
                ownerUserId: "owner-veln",
            },
            view: "private",
            generation: 5,
            content: { ...content, timed: true },
            summaryDueAt: null,
            profile: {
                revisionId: "profile-veln",
                automatic: {
                    learn: true,
                    summary: true,
                    topics: false,
                    title: false,
                },
            },
            categorization: {
                placementFolderIds: ["folder-veln"],
                intendedFolderIds: [],
                profileAssigned: true,
                resolution: "resolved",
            },
            hasEnhancementCredential: true,
            learnRunOpen: false,
            learnRunInFlight: false,
            learnRunReadyForReview: false,
            mail:
                kind === "mail"
                    ? { autoGenerated: false, unreadable: false, shared: false }
                    : null,
            summary: { exists: false, stale: false, jobActive: false },
            taskReview: { proposals: 0, followUps: 0 },
            at,
            phases: {
                categorize: {
                    state: "done",
                    reason: "categorized",
                    generation: 1,
                    at,
                },
                transcribe: {
                    state: "done",
                    reason: "content-available",
                    inputs: content,
                    generation: 1,
                    at,
                },
                learn: {
                    state: "done",
                    reason: "released",
                    inputs: content,
                    generation: 2,
                    at,
                },
                summary: {
                    state: "done",
                    generation: 3,
                    at,
                    inputs: content,
                    steps: {
                        summary: {
                            ...content,
                            state: "skipped",
                            reason: "held",
                            generation: 3,
                            outcome: { kind: "skipped", reason: "held" },
                        },
                    },
                },
            },
        };
        expect(planAdvance(facts).actions).toContainEqual(
            expect.objectContaining({ type: "queueSummary" }),
        );
        expect(
            planAdvance({
                ...facts,
                summaryDueAt: "2099-01-01T00:00:00.000Z",
                learnRunOpen: true,
                learnRunReadyForReview: true,
            }).actions.some((action) => action.type === "queueSummary"),
        ).toBe(false);
    });

    it.each<StepOutcome>([
        { kind: "done" },
        { kind: "skipped", reason: "shared" },
        {
            kind: "waiting",
            waitingFor: {
                kind: "learnReview",
                until: "2099-01-01T00:00:00.000Z",
            },
        },
        { kind: "failed", code: "lost", retryable: true },
    ])("maps $kind to durable state without hiding the reason", (outcome) => {
        const record = outcomeRecord(outcome);
        expect(record.state).toBe(outcome.kind);
        if (outcome.kind === "failed")
            expect(record).toMatchObject({ reason: "lost", retryable: true });
        if (outcome.kind === "waiting")
            expect(record.waitingFor).toEqual(outcome.waitingFor);
    });

    it.each([
        "transcribe",
        "learn",
        "summary",
        "share",
    ] as const)("shows interrupted %s with the existing retry action", (phase) => {
        const data: ItemProcessingPresentation = processingFixture({
            itemId: "item-veln",
            kind: "audio",
            legacy: false,
            manualOnly: false,
            phases: {
                [phase]: {
                    state: "failed",
                    reason: "lost",
                    retryable: true,
                    generation: 1,
                    at: "2026-10-01T00:00:00Z",
                },
            },
            profile: null,
            placements: [],
            intents: [],
            outputs: { transcript: false, summary: false, learn: false },
            processAgain: false,
            processAgainReason: null,
            learnFindingsWaiting: 0,
            taskReviewWaiting: 0,
            jobs: { transcription: null, summary: null },
            failures: [{ phase, reasonCode: "lost", retryAvailable: true }],
        });
        expect(deriveWorkflowStatus(data, "audio").status).toMatchObject({
            message: "failureInterrupted",
            action: "retry",
            params: { step: phase },
        });
    });
});
