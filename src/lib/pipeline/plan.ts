import type {
    ContentRevisionInput,
    PhaseRecord,
    PipelineAction,
    PipelineFacts,
    PipelinePlan,
    SummaryStepName,
} from "@/lib/pipeline/types";

function sameInput(
    record: PhaseRecord | undefined,
    input: ContentRevisionInput,
): boolean {
    return (
        record?.inputs?.contentSourceId === input.contentSourceId &&
        record.inputs.contentRevision === input.contentRevision
    );
}

function stepRequested(
    record: PhaseRecord | undefined,
    step: SummaryStepName,
    contentRevision: number,
    minimumGeneration?: number,
): boolean {
    const requested = record?.steps?.[step];
    return (
        requested?.contentRevision === contentRevision &&
        (minimumGeneration === undefined ||
            requested.generation >= minimumGeneration)
    );
}

function summaryStepMarker(
    facts: PipelineFacts,
    input: ContentRevisionInput,
    step: SummaryStepName,
    steps: NonNullable<PhaseRecord["steps"]>,
    reason: string,
): PipelineAction {
    steps[step] = {
        contentRevision: input.contentRevision,
        generation: facts.generation,
    };
    return {
        type: "markPhase",
        phase: "summary",
        record: {
            state: "pending",
            reason,
            generation: facts.generation,
            inputs: input,
            at: facts.at,
            steps: { ...steps },
        },
    };
}

function planMail(
    facts: PipelineFacts,
    input: ContentRevisionInput,
): PipelineAction[] {
    const mail = facts.mail;
    if (
        facts.settings?.mailAutoProcess === false ||
        !mail ||
        mail.autoGenerated ||
        mail.unreadable ||
        !facts.hasEnhancementCredential
    ) {
        return [];
    }

    const actions: PipelineAction[] = [];
    const steps = { ...facts.phases.summary?.steps };
    if (
        !stepRequested(facts.phases.summary, "summary", input.contentRevision)
    ) {
        actions.push({ type: "queueSummary", presetId: null, strict: false });
        actions.push(
            summaryStepMarker(facts, input, "summary", steps, "mail-arrival"),
        );
    }

    if (facts.settings?.autoLearn && !sameInput(facts.phases.learn, input)) {
        actions.push({ type: "startAutoLearnMail" });
        actions.push({
            type: "markPhase",
            phase: "learn",
            record: {
                state: "running",
                reason: "auto-mail-requested",
                generation: facts.generation,
                inputs: input,
                at: facts.at,
            },
        });
    }
    return actions;
}

function planReleasedAudio(
    facts: PipelineFacts,
    input: ContentRevisionInput,
    releaseGeneration: number,
): PipelineAction[] {
    const actions: PipelineAction[] = [];
    const steps = { ...facts.phases.summary?.steps };
    const notRequested = (step: SummaryStepName) =>
        !stepRequested(
            facts.phases.summary,
            step,
            input.contentRevision,
            releaseGeneration,
        );

    if (
        facts.settings?.autoSummarize &&
        !facts.summary.jobActive &&
        (!facts.summary.exists || facts.summary.stale) &&
        notRequested("summary")
    ) {
        actions.push({
            type: "queueSummary",
            presetId: facts.settings.autoSummarizePreset,
            strict: true,
        });
        actions.push(
            summaryStepMarker(facts, input, "summary", steps, "learn-released"),
        );
    }

    if (notRequested("topics")) {
        actions.push({ type: "queueTopics", strict: true });
        actions.push(
            summaryStepMarker(facts, input, "topics", steps, "learn-released"),
        );
    }

    if ((facts.settings?.autoGenerateTitle ?? true) && notRequested("title")) {
        actions.push({ type: "queueTitleJob" });
        actions.push(
            summaryStepMarker(facts, input, "title", steps, "learn-released"),
        );
    }
    return actions;
}

function planTranscriptAudio(
    facts: PipelineFacts,
    input: ContentRevisionInput & { timed: boolean },
): PipelineAction[] {
    const actions: PipelineAction[] = [];
    const steps = { ...facts.phases.summary?.steps };

    if (
        input.timed &&
        !stepRequested(facts.phases.summary, "topics", input.contentRevision)
    ) {
        actions.push({ type: "queueTopics", strict: false });
        actions.push(
            summaryStepMarker(facts, input, "topics", steps, "transcript"),
        );
    }

    if (
        facts.settings?.autoSummarize &&
        !stepRequested(facts.phases.summary, "summary", input.contentRevision)
    ) {
        actions.push({
            type: "queueSummary",
            presetId: facts.settings.autoSummarizePreset,
            strict: false,
        });
        actions.push(
            summaryStepMarker(facts, input, "summary", steps, "transcript"),
        );
    }
    return actions;
}

/** Decide the Stage 1 work due solely from durable item facts. */
export function planAdvance(facts: PipelineFacts): PipelinePlan {
    if (facts.view === "org") return { actions: [] };
    if (
        !facts.item.exists ||
        facts.item.deleted ||
        !facts.content ||
        (facts.item.kind === "audio" &&
            facts.content.contentSourceId !== "riffado")
    ) {
        return { actions: [], reason: "gone" };
    }

    const input = {
        contentSourceId: facts.content.contentSourceId,
        contentRevision: facts.content.contentRevision,
    };
    if (facts.item.kind === "mail") return { actions: planMail(facts, input) };

    if (facts.summaryDueAt) {
        if (
            sameInput(facts.phases.learn, input) &&
            facts.phases.learn?.state === "waiting" &&
            facts.phases.learn.generation >= facts.generation
        ) {
            return { actions: [] };
        }
        return {
            actions: [
                {
                    type: "markPhase",
                    phase: "learn",
                    record: {
                        state: "waiting",
                        reason: "auto-learn-hold",
                        generation: facts.generation,
                        inputs: input,
                        at: facts.at,
                    },
                },
            ],
        };
    }

    const learn = facts.phases.learn;
    if (
        learn?.state === "done" &&
        learn.reason === "released" &&
        sameInput(learn, input)
    ) {
        return {
            actions: planReleasedAudio(facts, input, learn.generation),
        };
    }
    return { actions: planTranscriptAudio(facts, facts.content) };
}
