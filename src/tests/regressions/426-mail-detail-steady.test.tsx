it("keeps the private summary visible and shows Saving while an Organization filing is pending", async () => {
    const app = openMail();
    const visibleSummary = await screen.findByText(summary);
    await file(orgFolder.name);
    await waitFor(() =>
        expect(app.writes.map(({ folderId }) => folderId)).toEqual([
            orgFolder.id,
        ]),
    );
    const chip = screen.getByRole("button", { name: "Remove from Design" });
    expect(chip.parentElement?.textContent).toContain("Saving…");
    await act(async () => invalidateItemProcessing(mail.id));
    expect(app.organizationReads()).toEqual([]);
    expect(screen.getByText(summary)).toBe(visibleSummary);

    app.holdSummary();
    const shared = projection([orgFolder], "2");
    app.setProcessing(shared);
    await act(async () =>
        app.writes[0].reply.resolve(
            Response.json({ placement: "shared", processing: shared }),
        ),
    );
    await waitFor(() =>
        expect(
            app.organizationReads().some((url) => url.includes("/summary?")),
        ).toBe(true),
    );
    expect(screen.getByText(summary)).toBe(visibleSummary);
    expect(chip.parentElement?.textContent).not.toContain("Saving…");
    await act(async () =>
        app.summaryReads
            .at(-1)
            ?.resolve(summaryResponse("The Organization summary.")),
    );
    expect(await screen.findByText("The Organization summary.")).toBeTruthy();
});

it("removes only the refused Organization chip and saves the next mail filing", async () => {
    const app = openMail();
    await screen.findByText(summary);
    await file(orgFolder.name);
    await file(privateFolder.name);
    expect(app.writes.map(({ folderId }) => folderId)).toEqual([orgFolder.id]);
    const notes = screen.getByRole("button", { name: "Remove from Notes" });

    await act(async () =>
        app.writes[0].reply.resolve(
            Response.json(
                { code: "SHARE_REQUIREMENTS_UNMET", error: "Share blocked" },
                { status: 409 },
            ),
        ),
    );
    expect(
        screen.queryByRole("button", { name: "Remove from Design" }),
    ).toBeNull();
    expect(screen.getByRole("button", { name: "Remove from Notes" })).toBe(
        notes,
    );
    expect(app.writes.map(({ folderId }) => folderId)).toEqual([
        orgFolder.id,
        privateFolder.id,
    ]);
    expect(mocks.error).toHaveBeenCalled();

    const filed = projection([privateFolder], "2");
    app.setProcessing(filed);
    await act(async () =>
        app.writes[1].reply.resolve(
            Response.json({ placement: "filed", processing: filed }),
        ),
    );
    expect(
        screen.getByRole("button", { name: "Remove from Notes" }),
    ).toBeTruthy();
    expect(app.organizationReads()).toEqual([]);
    expect(screen.getByText(summary)).toBeTruthy();
});

it("keeps the open message body mounted while the owner switches to the Organization row", async () => {
    const app = openMail(projection([orgFolder]));
    await screen.findByText(message);
    fireEvent.click(screen.getByRole("button", { name: "Show formatted" }));
    const body = await screen.findByTitle("Formatted mail");
    app.holdContent();

    await act(async () => {
        window.history.replaceState(
            { mobileView: "detail" },
            "",
            `/dashboard?recording=${mail.id}&folder=${orgFolder.id}&view=org`,
        );
        window.dispatchEvent(new PopStateEvent("popstate"));
    });
    expect(
        app.organizationReads().some((url) => url.includes("content=1")),
    ).toBe(true);
    expect(screen.getByTitle("Formatted mail")).toBe(body);
    await act(async () =>
        app.contentReads[0].resolve(Response.json(mailDetail)),
    );
    expect(screen.getByTitle("Formatted mail")).toBe(body);
});

it("keeps the mail summary and open remarks through a version refresh", async () => {
    const app = openMail();
    const visibleSummary = await screen.findByText(summary);
    fireEvent.click(screen.getByRole("button", { name: "Summary remarks" }));
    await screen.findByText(storedRemark);
    const dialog = screen.getByRole("dialog", { name: "Summary remarks" });
    const field = screen.getByLabelText<HTMLTextAreaElement>("New remark");
    fireEvent.change(field, { target: { value: "Keep this draft." } });

    app.holdSummary();
    app.setProcessing(projection([], "2"));
    await act(async () => invalidateItemProcessing(mail.id));
    await waitFor(() => expect(app.summaryReads).toHaveLength(1));
    expect(screen.getByText(summary)).toBe(visibleSummary);
    expect(screen.getByRole("dialog", { name: "Summary remarks" })).toBe(
        dialog,
    );
    expect(screen.getByText(storedRemark)).toBeTruthy();
    expect(field.value).toBe("Keep this draft.");

    const refreshedSummary = "The workshop is confirmed for noon.";
    await act(async () =>
        app.summaryReads[0].resolve(summaryResponse(refreshedSummary, 1)),
    );
    expect(screen.getByText(refreshedSummary)).toBeTruthy();
    expect(screen.getByRole("dialog", { name: "Summary remarks" })).toBe(
        dialog,
    );
    expect(screen.getByText(storedRemark)).toBeTruthy();
    expect(field.value).toBe("Keep this draft.");
});
